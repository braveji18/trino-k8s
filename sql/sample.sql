
SELECT
 dt
 , PARAM_NM
 , AVG(MEAN_VALUE) AS MEAN_VALUE
 , AVG(MAX_VALUE) AS  MAX_VALUE
 , AVG(END_VALUE) AS END_VALUE

FROM (
   VALUES
      ('2026-01-01', MAP(ARRAY['TESLA', 'NVIDIA'], ARRAY[300, 244]), ARRAY[310, 249]), ARRAY[310, 247]) ),
      ('2026-01-02', MAP(ARRAY['TESLA', 'NVIDIA'], ARRAY[300, 244]), ARRAY[310, 249]), ARRAY[310, 247]) ),
      ('2026-01-03', MAP(ARRAY['TESLA', 'NVIDIA'], ARRAY[300, 244]), ARRAY[310, 249]), ARRAY[310, 247]) ),
      ('2026-01-04', MAP(ARRAY['TESLA', 'NVIDIA'], ARRAY[300, 244]), ARRAY[310, 249]), ARRAY[310, 247]) )
) AS today_stock(dt, company_code,stock_min,stock_max,stock_end)
CROSS JOIN UNNEST(company_code,stock_min,stock_max,stock_end) AS t(PARAM_NM,MEAN_VALUE,MAX_VALUE,END_VALUE);
WHERE
 dt BETWEEN '2026-01-01' AND '2026-01-10'
GROUP BY dt,  PARAM_NM

